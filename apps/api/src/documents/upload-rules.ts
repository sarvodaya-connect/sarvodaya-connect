/** Upload rules shared with the mobile app (SC-25 / SC-47): PDF, JPG or PNG, up to 10 MB. */

export const MAX_DOCUMENT_BYTES = 10_000_000;

export const ALLOWED_CONTENT_TYPES = {
  'application/pdf': ['.pdf'],
  'image/jpeg': ['.jpg', '.jpeg'],
  'image/png': ['.png'],
} as const satisfies Record<string, readonly string[]>;

export type AllowedContentType = keyof typeof ALLOWED_CONTENT_TYPES;

export const DOCUMENT_TYPES = [
  'AUDIT_REPORT',
  'AGM_MINUTES',
  'OFFICE_BEARER_LIST',
  'MEMBERS_LIST',
  'REGISTRATION',
  'FINANCE',
  'ACTIVITY_EVIDENCE',
  'OTHER',
] as const;

export type DocumentTypeValue = (typeof DOCUMENT_TYPES)[number];

export const DOCUMENT_STATUSES = [
  'DRAFT',
  'SUBMITTED',
  'APPROVED',
  'REJECTED',
] as const;

export type DocumentStatusValue = (typeof DOCUMENT_STATUSES)[number];

/** The file extension that matches the content type, used in storage keys. */
export function extensionFor(
  fileName: string,
  contentType: AllowedContentType,
): string | null {
  const lower = fileName.toLowerCase();
  const extension = ALLOWED_CONTENT_TYPES[contentType].find((candidate) =>
    lower.endsWith(candidate),
  );
  return extension ?? null;
}

/** Storage keys only contain ids generated by the API, never user-supplied names. */
export function storageKeyFor(input: {
  societyId: string;
  documentId: string;
  extension: string;
}): string {
  return `societies/${input.societyId}/documents/${input.documentId}${input.extension}`;
}
