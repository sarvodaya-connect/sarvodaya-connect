/**
 * Upload rules shared with the mobile app (SC-25 / SC-47): PDF, JPG or PNG,
 * up to 10 MB by default. DOCUMENT_MAX_UPLOAD_BYTES can lower or raise the
 * limit up to UPLOAD_SIZE_CEILING, which stays well inside what a pre-signed
 * single PUT to S3 accepts. Files never pass through API Gateway.
 */

export const MAX_DOCUMENT_BYTES = 10_000_000;
export const UPLOAD_SIZE_CEILING = 50_000_000;

/** The configured upload limit in bytes; a missing or invalid value means 10 MB. */
export function maxUploadBytes(value: string | undefined): number {
  const parsed = Number(value);
  return Number.isInteger(parsed) && parsed > 0 && parsed <= UPLOAD_SIZE_CEILING
    ? parsed
    : MAX_DOCUMENT_BYTES;
}

/** The four annual documents to the Registrar. Each needs its financial year. */
export const REGISTRAR_DOCUMENT_TYPES = [
  'AUDIT_REPORT',
  'AGM_MINUTES',
  'OFFICE_BEARER_LIST',
  'MEMBERS_LIST',
] as const;

export function isRegistrarDocument(type: string): boolean {
  return (REGISTRAR_DOCUMENT_TYPES as readonly string[]).includes(type);
}

/** SHA-256 in base64, as S3 expects in x-amz-checksum-sha256. */
export const SHA256_BASE64 = /^[A-Za-z0-9+/]{43}=$/;

export const ALLOWED_CONTENT_TYPES = {
  'application/pdf': ['.pdf'],
  'image/jpeg': ['.jpg', '.jpeg'],
  'image/png': ['.png'],
} as const satisfies Record<string, readonly string[]>;

export type AllowedContentType = keyof typeof ALLOWED_CONTENT_TYPES;

export const DOCUMENT_TYPES = [
  'AUDIT_REPORT',
  'AGM_MINUTES',
  'OFFICE_BEARER_LIST',
  'MEMBERS_LIST',
  'REGISTRATION',
  'FINANCE',
  'ACTIVITY_EVIDENCE',
  'OTHER',
] as const;

export type DocumentTypeValue = (typeof DOCUMENT_TYPES)[number];

export const DOCUMENT_STATUSES = [
  'DRAFT',
  'SUBMITTED',
  'APPROVED',
  'REJECTED',
] as const;

export type DocumentStatusValue = (typeof DOCUMENT_STATUSES)[number];

/** The file extension that matches the content type, used in storage keys. */
export function extensionFor(
  fileName: string,
  contentType: AllowedContentType,
): string | null {
  const lower = fileName.toLowerCase();
  const extension = ALLOWED_CONTENT_TYPES[contentType].find((candidate) =>
    lower.endsWith(candidate),
  );
  return extension ?? null;
}

/**
 * Storage keys only contain ids and values generated by the API, never names
 * or other personal data: societies/{id}/{type}/{fy}/{uuid}.pdf, where the
 * year is "2025-26" or "general" for documents without a financial year.
 */
export function storageKeyFor(input: {
  societyId: string;
  documentType: DocumentTypeValue;
  financialYear: number | null;
  documentId: string;
  extension: string;
}): string {
  const type = input.documentType.toLowerCase().replaceAll('_', '-');
  const year =
    input.financialYear == null
      ? 'general'
      : `${input.financialYear}-${String((input.financialYear + 1) % 100).padStart(2, '0')}`;
  return `societies/${input.societyId}/${type}/${year}/${input.documentId}${input.extension}`;
}
