/**
 * Storage boundary for document files. Business logic only uses this
 * interface; the local driver (development) and the Amazon S3 driver both
 * hand clients short-lived pre-signed URLs, so file bytes never pass through
 * the documents service.
 */
export const DOCUMENT_STORAGE = Symbol('DOCUMENT_STORAGE');

export interface PresignedRequest {
  method: 'PUT' | 'GET';
  url: string;
  /** Headers the client must send with the request. */
  headers: Record<string, string>;
  expiresAt: string;
}

export interface StoredObjectInfo {
  sizeBytes: number;
}

export interface DocumentStorage {
  readonly driver: 'local' | 's3';

  /** A URL the client uses to upload the file directly to storage. */
  createUploadRequest(input: {
    key: string;
    contentType: string;
    sizeBytes: number;
  }): Promise<PresignedRequest>;

  /** A URL the client uses to download the file directly from storage. */
  createDownloadRequest(input: {
    key: string;
    fileName: string;
    contentType: string;
  }): Promise<PresignedRequest>;

  /** Information about a stored file, or null when nothing has been uploaded. */
  getObjectInfo(key: string): Promise<StoredObjectInfo | null>;
}

/** Storage could not be reached. The message is safe to log but not to return. */
export class StorageUnavailableError extends Error {}

/** Keys are generated by the API; anything else is refused before reaching a driver. */
export function assertSafeStorageKey(key: string): void {
  if (
    !/^[a-z0-9][a-z0-9/._-]{0,500}$/i.test(key) ||
    key.includes('..') ||
    key.includes('//') ||
    key.endsWith('/')
  ) {
    throw new Error('Invalid storage key');
  }
}

/** A filename that is safe inside a Content-Disposition header. */
export function safeDownloadName(fileName: string): string {
  const cleaned = fileName.replace(/[^\w .()-]/g, '_').trim();
  return cleaned.length > 0 ? cleaned.slice(0, 200) : 'document';
}
